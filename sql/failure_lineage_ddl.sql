DROP DATABASE IF EXISTS failure_lineage;
CREATE DATABASE failure_lineage;
USE failure_lineage;

-- 1. USERS
CREATE TABLE users (
    user_id INT AUTO_INCREMENT PRIMARY KEY,
    username VARCHAR(100) NOT NULL UNIQUE,
    role ENUM('admin', 'investigator', 'user') NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

-- 2. MODELS
CREATE TABLE models (
    model_id INT AUTO_INCREMENT PRIMARY KEY,
    model_name VARCHAR(150) NOT NULL,
    model_version VARCHAR(50) NOT NULL,
    description TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

-- 3. DATASETS
CREATE TABLE datasets (
    dataset_id INT AUTO_INCREMENT PRIMARY KEY,
    dataset_name VARCHAR(150) NOT NULL,
    description TEXT,
    record_count INT NOT NULL DEFAULT 0,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

-- 4. MODEL-DATASET RELATIONSHIP
CREATE TABLE model_dataset (
    model_id INT NOT NULL,
    dataset_id INT NOT NULL,
    usage_purpose VARCHAR(100) NOT NULL,
    PRIMARY KEY (model_id, dataset_id),
    FOREIGN KEY (model_id) REFERENCES models(model_id),
    FOREIGN KEY (dataset_id) REFERENCES datasets(dataset_id)
) ENGINE=InnoDB;

-- 5. EMAILS / INPUT RECORDS
CREATE TABLE emails (
    email_id INT AUTO_INCREMENT PRIMARY KEY,
    sender VARCHAR(255),
    subject VARCHAR(255),
    email_text TEXT NOT NULL,
    metadata JSON,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

-- 6. PREDICTIONS GENERATED BY THE MODEL
CREATE TABLE predictions (
    prediction_id INT AUTO_INCREMENT PRIMARY KEY,
    model_id INT NOT NULL,
    email_id INT NOT NULL,
    predicted_class VARCHAR(50) NOT NULL,
    confidence_score DECIMAL(5,3),
    predicted_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (model_id) REFERENCES models(model_id),
    FOREIGN KEY (email_id) REFERENCES emails(email_id),
    CHECK (
        confidence_score IS NULL
        OR confidence_score BETWEEN 0 AND 1
    )
) ENGINE=InnoDB;

-- 7. ACTUAL / VERIFIED RESULTS
CREATE TABLE actual_results (
    actual_id INT AUTO_INCREMENT PRIMARY KEY,
    prediction_id INT NOT NULL UNIQUE,
    actual_class VARCHAR(50) NOT NULL,
    is_correct TINYINT(1) NOT NULL DEFAULT 0,
    verified_by INT NOT NULL,
    verified_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (prediction_id)
        REFERENCES predictions(prediction_id),
    FOREIGN KEY (verified_by)
        REFERENCES users(user_id),
    CHECK (is_correct IN (0, 1))
) ENGINE=InnoDB;

-- 8. FAILURE CATEGORIES
CREATE TABLE failure_types (
    failure_type_id INT AUTO_INCREMENT PRIMARY KEY,
    failure_type_name VARCHAR(100) NOT NULL UNIQUE,
    description TEXT
) ENGINE=InnoDB;

-- 9. FAILURES FOUND DURING VERIFICATION
CREATE TABLE failures (
    failure_id INT AUTO_INCREMENT PRIMARY KEY,
    prediction_id INT NOT NULL UNIQUE,
    failure_type_id INT NOT NULL,
    description TEXT NOT NULL,
    feedback_id INT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (prediction_id)
        REFERENCES predictions(prediction_id),
    FOREIGN KEY (failure_type_id)
        REFERENCES failure_types(failure_type_id)
) ENGINE=InnoDB;

-- 10. INVESTIGATOR / USER FEEDBACK
CREATE TABLE feedback (
    feedback_id INT AUTO_INCREMENT PRIMARY KEY,
    prediction_id INT NOT NULL,
    user_id INT NOT NULL,
    feedback_text TEXT NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (prediction_id)
        REFERENCES predictions(prediction_id),
    FOREIGN KEY (user_id)
        REFERENCES users(user_id)
) ENGINE=InnoDB;

-- Add the feedback foreign key after both tables exist.
ALTER TABLE failures
ADD CONSTRAINT fk_failures_feedback
FOREIGN KEY (feedback_id) REFERENCES feedback(feedback_id);

-- 11. DATA LINEAGE
CREATE TABLE data_lineage (
    lineage_id INT AUTO_INCREMENT PRIMARY KEY,
    prediction_id INT NOT NULL UNIQUE,
    email_id INT NOT NULL,
    dataset_id INT NOT NULL,
    model_id INT NOT NULL,
    actual_id INT NOT NULL,
    failure_id INT NULL,
    feedback_id INT NULL,
    model_version VARCHAR(50) NOT NULL,
    preprocessing_steps TEXT,
    feature_extraction TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (prediction_id)
        REFERENCES predictions(prediction_id),
    FOREIGN KEY (email_id)
        REFERENCES emails(email_id),
    FOREIGN KEY (dataset_id)
        REFERENCES datasets(dataset_id),
    FOREIGN KEY (model_id)
        REFERENCES models(model_id),
    FOREIGN KEY (actual_id)
        REFERENCES actual_results(actual_id),
    FOREIGN KEY (failure_id)
        REFERENCES failures(failure_id),
    FOREIGN KEY (feedback_id)
        REFERENCES feedback(feedback_id)
) ENGINE=InnoDB;

-- 12. FAILURE CATEGORY AUDIT LOG
CREATE TABLE failure_audit_log (
    audit_id INT AUTO_INCREMENT PRIMARY KEY,
    failure_id INT NOT NULL,
    old_failure_type_id INT NOT NULL,
    new_failure_type_id INT NOT NULL,
    changed_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (failure_id) REFERENCES failures(failure_id),
    FOREIGN KEY (old_failure_type_id)
        REFERENCES failure_types(failure_type_id),
    FOREIGN KEY (new_failure_type_id)
        REFERENCES failure_types(failure_type_id)
) ENGINE=InnoDB;

-- 13. INDEXES
CREATE INDEX idx_predictions_model
    ON predictions(model_id);

CREATE INDEX idx_predictions_class
    ON predictions(predicted_class);

CREATE INDEX idx_actual_class
    ON actual_results(actual_class);

CREATE INDEX idx_failures_type
    ON failures(failure_type_id);

-- =========================================================
-- TRIGGER 1: Automatically calculate correctness.
-- Runs before an actual result is inserted.
-- =========================================================

DELIMITER $$

CREATE TRIGGER trg_set_is_correct
BEFORE INSERT ON actual_results
FOR EACH ROW
BEGIN
    DECLARE v_predicted_class VARCHAR(50);

    SELECT predicted_class
    INTO v_predicted_class
    FROM predictions
    WHERE prediction_id = NEW.prediction_id;

    SET NEW.is_correct =
        IF(v_predicted_class = NEW.actual_class, 1, 0);
END$$

-- =========================================================
-- TRIGGER 2: Automatically create a failure when incorrect.
-- Initial category is 1; the procedure may refine it later.
-- =========================================================

CREATE TRIGGER trg_auto_create_failure
AFTER INSERT ON actual_results
FOR EACH ROW
BEGIN
    DECLARE v_predicted_class VARCHAR(50);

    IF NEW.is_correct = 0 THEN

        SELECT predicted_class
        INTO v_predicted_class
        FROM predictions
        WHERE prediction_id = NEW.prediction_id;

        INSERT INTO failures (
            prediction_id,
            failure_type_id,
            description
        )
        VALUES (
            NEW.prediction_id,
            1,
            CONCAT(
                'Predicted ',
                v_predicted_class,
                ' but verified actual class was ',
                NEW.actual_class,
                '.'
            )
        );

    END IF;
END$$

-- =========================================================
-- TRIGGER 3: Audit changes to failure categories.
-- =========================================================

CREATE TRIGGER trg_audit_failure_type
AFTER UPDATE ON failures
FOR EACH ROW
BEGIN
    IF NOT (
        OLD.failure_type_id <=> NEW.failure_type_id
    ) THEN

        INSERT INTO failure_audit_log (
            failure_id,
            old_failure_type_id,
            new_failure_type_id
        )
        VALUES (
            NEW.failure_id,
            OLD.failure_type_id,
            NEW.failure_type_id
        );

    END IF;
END$$

DELIMITER ;

-- =========================================================
-- VIEW: Detailed investigation information
-- =========================================================

CREATE VIEW v_failure_investigation AS
SELECT
    f.failure_id,
    p.prediction_id,
    m.model_name,
    m.model_version,
    e.subject,
    e.email_text,
    p.predicted_class,
    ar.actual_class,
    ar.is_correct,
    ft.failure_type_name,
    f.description AS failure_description,
    d.dataset_name,
    fb.feedback_text,
    f.created_at AS failure_created_at
FROM failures f
JOIN predictions p
    ON f.prediction_id = p.prediction_id
JOIN models m
    ON p.model_id = m.model_id
JOIN emails e
    ON p.email_id = e.email_id
JOIN actual_results ar
    ON p.prediction_id = ar.prediction_id
JOIN failure_types ft
    ON f.failure_type_id = ft.failure_type_id
LEFT JOIN data_lineage dl
    ON p.prediction_id = dl.prediction_id
LEFT JOIN datasets d
    ON dl.dataset_id = d.dataset_id
LEFT JOIN feedback fb
    ON f.feedback_id = fb.feedback_id;

